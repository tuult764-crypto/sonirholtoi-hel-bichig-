  var TZ = 'Asia/Ulaanbaatar';
  function todayStr() {
    try {
      var parts = new Intl.DateTimeFormat('en-GB', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(new Date());
      var part = {}; parts.forEach(function (x) { if (x.type !== 'literal') part[x.type] = x.value; });
      return part.year + '-' + part.month + '-' + part.day;
    } catch (e) { return new Date().toISOString().slice(0, 10); }
  }
  function dayNo(s) { return Math.round(Date.parse(s + 'T00:00:00Z') / 864e5); }
  function addDays(s, n) { return new Date((dayNo(s) + n) * 864e5).toISOString().slice(0, 10); }

  var scheduled = {};
  ENTRIES.forEach(function (e) { if (e.date) scheduled[e.date] = e; });
  var pool = ENTRIES.filter(function (e) { return !e.date; });

  function forDate(s) {
    if (scheduled[s]) return scheduled[s];
    if (!pool.length) return null;
    var n = pool.length;
    return pool[((dayNo(s) % n) + n) % n];
  }
