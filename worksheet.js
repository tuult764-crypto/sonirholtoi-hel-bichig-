function parse(x) { return JSON.parse(String(x).replace(/^```(?:json)?/i, '').replace(/```\s*$/, '').trim()); }
function clean(d) {
  const L = Array.isArray(d.levels) ? d.levels : [];
  const levels = Object.keys(LEVELS).map(n => ({ level: n, questions: [].concat(...L.filter(l => l && l.level === n).map(l => Array.isArray(l.questions) ? l.questions : [])).map(x => ({ q: str(x && x.q, 500), a: str(x && x.a, 600) })).filter(x => x.q).slice(0, 8) })).filter(l => l.questions.length);
  if (!levels.length) throw new Error('асуулт дутуу');
  return { title: str(d.title, 90) || 'Ажлын хуудас', levels };
}
const t = (text, o = {}) => new Paragraph({ spacing: { after: o.after ?? 120 }, children: [new TextRun({ text, font: F, size: o.size || 24, bold: o.bold, color: o.color })] });
async function make(d) {
  const c = [t('Нэр: ______________________   Анги: ________   Огноо: ____________', { after: 240 }), t(d.title, { size: 34, bold: true, color: '3B2FBF', after: 240 })];
  let n = 0;
  d.levels.forEach((l, i) => {
    c.push(t(`${i + 1}. ${l.level}`, { size: 28, bold: true, after: 100 }));
    l.questions.forEach(x => { c.push(t(`${++n}) ${x.q}`, { after: 80 })); for (let k = 0; k < (l.level === 'Сэргээн санах' ? 1 : 3); k++) c.push(t('_'.repeat(70), { after: 60, color: '999999' })); });
    c.push(t('', { after: 120 }));
  });
  c.push(new Paragraph({ children: [new PageBreak()] })); c.push(t('Хариу (зөвхөн багшид)', { size: 30, bold: true, after: 160 })); n = 0;
  d.levels.forEach(l => { c.push(t(l.level, { bold: true, after: 60 })); l.questions.forEach(x => c.push(t(`${++n}) ${x.a || '—'}`, { after: 60 }))); });
  return Packer.toBase64String(new Document({ sections: [{ properties: { page: { margin: { top: 1000, bottom: 1000, left: 1100, right: 1100 } } }, children: c }] }));
}
